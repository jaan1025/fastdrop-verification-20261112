import { keccak256, toBytes } from "viem"
import { hexToBytes, toIsoString } from "@repo/shared/utils"
import type { ScheduleCodeProjection, ScheduleInput } from "./types"

/**
 * [golden-test] Derives the human scheduleCode (6 hex chars) from a
 * `ScheduleInput` and hashes it to the on-chain preset key (keccak256). Byte
 * output is an idempotency key — must stay byte-identical to legacy generation.
 *
 * The schedule code is a LOCK identity: its inputs are `ScheduleInput` vesting
 * fields and its consumers are the vesting/lock flows, so the grammar lives with
 * the lock family. Owns derivation only; the wire
 * `normalizeScheduleCode`/`splitScheduleCode` live in `@repo/acs-client/model`
 * and are NOT imported here — the boundary is intentional (no cross-import).
 */

// `useCalendarMonth` and `pieceDuration` are non-user-editable in legacy
// (defaults `true` / `"0"`) but participate in the hash input. Kept constant so
// codes generated here match codes generated by legacy with the same form fields.
const HASH_USE_CALENDAR_MONTH = "true"
const HASH_PIECE_DURATION = "0"

/**
 * Derives the string-percent projection of the canonical input that
 * `deriveScheduleCode` consumes — the single mapping that replaces every caller's
 * hand-mapping between the two legacy form types (analysis L2).
 */
export function toScheduleCodeProjection(input: ScheduleInput): ScheduleCodeProjection {
  return {
    name: input.name,
    cliffValue: input.cliffValue,
    cliffUnit: input.cliffUnit,
    durationValue: input.durationValue,
    durationUnit: input.durationUnit,
    unlockInterval: input.interval,
    useFixedStartTime: input.useFixedStartTime,
    // Normalize the fixed start to canonical Z-ISO before it enters the hash, so
    // the code is addressed by the INSTANT, not the input spelling (zoneless
    // "2026-06-22T10:26" and "…:00.000Z" hash identically). Empty = flexible.
    startTime: input.startTime ? toIsoString(input.startTime) : "",
    startUnlockPercentage: String(input.startUnlockPercent),
    cliffUnlockPercentage: String(input.cliffUnlockPercent),
  }
}

export function deriveScheduleCode(input: ScheduleInput): string {
  const p = toScheduleCodeProjection(input)
  const parts = [
    p.name,
    String(p.cliffValue),
    p.cliffUnit,
    String(p.durationValue),
    p.durationUnit,
    p.unlockInterval,
    HASH_USE_CALENDAR_MONTH,
    String(p.useFixedStartTime),
    p.startTime,
    p.startUnlockPercentage,
    p.cliffUnlockPercentage,
    HASH_PIECE_DURATION,
  ].join("-")
  const hash = keccak256(toBytes(parts))
  // 6 trailing hex chars of the 32-byte keccak (without leading 0x).
  return hash.slice(-6)
}

/** 32-byte keccak hash of the human scheduleCode — the on-chain EVM preset key. */
export function hashScheduleCode(scheduleCode: string): `0x${string}` {
  return keccak256(toBytes(scheduleCode))
}

/** Same keccak hash as a byte array — the Solana PDA configurator seed. */
export function scheduleCodeHashBytes(scheduleCode: string): Uint8Array {
  return hexToBytes(hashScheduleCode(scheduleCode))
}
